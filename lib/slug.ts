// Puro y sin dependencias: lo usan el servidor (direcciones de eventos y
// clientes) y el navegador (zonas del mapa).
export function slugify(texto: string): string {
  return texto
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}
